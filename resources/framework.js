function text(text, x, y, color, centered = false, scale = 1) {
    if (centered) {
        x -= Math.floor(text.length / 2) * scale * 6;
    }
    text = text.toUpperCase();
    const textWidth = text.split('').reduce((width, char) => {
        return width + (letters[char] ? (letters[char][0].length + 1) * scale : 0);
    }, 0) - scale;

    if (centered) {
        x -= Math.floor(textWidth / 2);
    }

    for (let charIndex = 0; charIndex < text.length; charIndex++) {
        const char = text[charIndex];
        if (!letters[char]) continue;
        for (let i = 0; i < letters[char].length; i++) {
            for (let j = 0; j < letters[char][i].length; j++) {
                if (letters[char][i][j] === '1') {
                    rect(x + j * scale, y + i * scale, scale, scale, color);
                } else {
                    rect(x + j * scale, y + i * scale, scale, scale, 'black');
                }
            }
        }
        x += (letters[char][0].length + 1) * scale;
    }
}
function render5x5(x, y, string, scale = 1) {
    const gridSize = 5;
    for (let i = 0; i < string.length; i++) {
        const char = string[i];
        const gridX = x + (i % gridSize) * scale;
        const gridY = y + Math.floor(i / gridSize) * scale;
        rect(gridX, gridY, scale, scale, char);
    }
}
