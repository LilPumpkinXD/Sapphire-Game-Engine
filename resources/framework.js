function pixel(x, y, color) {
    ctx.fillStyle = color;
    ctx.fillRect(x * 1000 / scale, y * 1000 / scale, 1000 / scale, 1000 / scale);
}
function rect(x, y, w, h, color) {
    ctx.fillStyle = color;
    ctx.fillRect(x * 1000 / scale, y * 1000 / scale, w * 1000 / scale, h * 1000 / scale);
}

function clear(opacity) {
    if (opacity) {
        ctx.fillStyle = `rgba(0, 0, 0, ${opacity})`;
        ctx.fillRect(0, 0, cw, ch);
    } else {
        ctx.clearRect(0, 0, cw, ch);
    }
}
